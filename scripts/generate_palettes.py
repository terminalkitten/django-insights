"""Generate palettes.py from the shadcn/ui themes.ts, then ruff format the result"""

from __future__ import annotations

import math
import re
import sys
import urllib.request
from pathlib import Path

SOURCE = (
    'https://raw.githubusercontent.com/shadcn-ui/ui/main/apps/v4/registry/themes.ts'
)
TARGET = Path(__file__).parent.parent / 'django_insights' / 'palettes.py'
BASES = ('neutral', 'stone', 'zinc', 'mauve', 'olive', 'mist', 'taupe')
OKLCH = re.compile(
    r'oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)(?:\s*/\s*([\d.]+)%)?\s*\)'
)


def linear_srgb(lightness: float, chroma: float, hue: float) -> tuple[float, ...]:
    a = chroma * math.cos(math.radians(hue))
    b = chroma * math.sin(math.radians(hue))
    l_ = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (
        4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
        -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
        -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_,
    )


def in_gamut(channels: tuple[float, ...]) -> bool:
    return all(-0.0005 <= channel <= 1.0005 for channel in channels)


def encode(channel: float) -> int:
    channel = min(max(channel, 0.0), 1.0)
    value = (
        12.92 * channel
        if channel <= 0.0031308
        else 1.055 * channel ** (1 / 2.4) - 0.055
    )
    return round(value * 255)


def to_rgb(lightness: float, chroma: float, hue: float) -> tuple[int, ...]:
    """Colors outside sRGB lose chroma until they fit, like a browser does"""
    low, high = 0.0, chroma
    if not in_gamut(linear_srgb(lightness, chroma, hue)):
        for _ in range(30):
            middle = (low + high) / 2
            if in_gamut(linear_srgb(lightness, middle, hue)):
                low = middle
            else:
                high = middle
        chroma = low
    return tuple(encode(channel) for channel in linear_srgb(lightness, chroma, hue))


def to_hex(value: str, over: str | None = None) -> str:
    """An oklch color as hex, with an alpha it is mixed onto the color `over`"""
    match = OKLCH.fullmatch(value.strip())
    if not match:
        raise ValueError(f'Not an oklch color: {value}')
    lightness, chroma, hue = (float(part) for part in match.groups()[:3])
    red, green, blue = to_rgb(lightness, chroma, hue)
    if match.group(4) is not None and over:
        alpha = float(match.group(4)) / 100
        under = tuple(int(over[index : index + 2], 16) for index in (1, 3, 5))
        red, green, blue = (
            round(color * alpha + below * (1 - alpha))
            for color, below in zip((red, green, blue), under, strict=True)
        )
    return f'#{red:02x}{green:02x}{blue:02x}'


def parse(source: str) -> dict[str, dict[str, dict[str, str]]]:
    themes: dict[str, dict[str, dict[str, str]]] = {}
    for block in re.split(r'\n  \{\n    name: ', source)[1:]:
        named = re.match(r'"([\w-]+)"', block)
        if named is None:
            raise ValueError('A theme without a name')
        name = named.group(1)
        themes[name] = {}
        for mode in ('light', 'dark'):
            part = re.search(rf'      {mode}: \{{\n(.*?)\n      \}},', block, re.S)
            if part is None:
                raise ValueError(f'The {name} theme has no {mode} colors')
            themes[name][mode] = dict(
                re.findall(r'"?([\w-]+)"?: "([^"]+)"', part.group(1))
            )
    return themes


def convert(variables: dict[str, str]) -> dict[str, str]:
    """Hex values by key, translucent colors are mixed onto the card color"""
    card = to_hex(variables['card']) if 'card' in variables else None
    return {
        key.replace('-', '_'): to_hex(value, over=card)
        for key, value in variables.items()
        if value.startswith('oklch')
    }


def main() -> None:
    if len(sys.argv) > 1:
        source = Path(sys.argv[1]).read_text()
    else:
        source = urllib.request.urlopen(SOURCE, timeout=30).read().decode()

    themes = parse(source)
    bases = {
        name: {mode: convert(themes[name][mode]) for mode in ('light', 'dark')}
        for name in BASES
    }
    accents = {
        name: {mode: convert(themes[name][mode]) for mode in ('light', 'dark')}
        for name in themes
        if name not in BASES
    }
    TARGET.write_text(
        '"""The shadcn/ui themes as hex colors, generated by scripts/generate_palettes.py"""\n\n'
        f'BASES = {bases!r}\n\nACCENTS = {accents!r}\n'
    )


if __name__ == '__main__':
    main()
